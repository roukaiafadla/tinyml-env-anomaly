"""Convert the trained float autoencoder to a fully INT8 TFLite model and recompute
the anomaly threshold on the QUANTIZED model.

WHY recompute: INT8 rounding adds noise to the reconstruction error, so the float
threshold is not valid for the model that will actually run on the ESP32.

Synthetic pipeline test:
    python ml/convert_tflite.py --train data/synthetic/fake_normal.csv --model-dir models/synthetic
Real data (use the same --train files and --block as in training):
    python ml/convert_tflite.py --train data/raw/session_A.csv data/raw/session_B.csv --model-dir models/real

Outputs in --model-dir: model_int8.tflite, thresholds_int8.json, model_data.h, model_params.h
"""
import argparse
import json
import os
import sys

import keras
import numpy as np
import tensorflow as tf
from sklearn.metrics import precision_recall_fscore_support, roc_auc_score

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from train_autoencoder import block_split, load  # noqa: E402


def get_interpreter_class():
    # tf.lite.Interpreter is deprecated; the LiteRT package is its replacement.
    try:
        from ai_edge_litert.interpreter import Interpreter
        return Interpreter
    except ImportError:
        pass
    try:
        return tf.lite.Interpreter
    except AttributeError:
        raise SystemExit("No TFLite interpreter found. Run: pip install ai-edge-litert")


def run_int8(interp, X):
    """Quantize inputs, run the INT8 model sample by sample, dequantize outputs.

    This mirrors exactly what the ESP32 firmware will do:
    q = round(x / s_in) + z_in  ->  invoke  ->  y = (q_out - z_out) * s_out
    """
    inp = interp.get_input_details()[0]
    out = interp.get_output_details()[0]
    s_in, z_in = inp["quantization"]
    s_out, z_out = out["quantization"]
    Q = np.clip(np.round(X / s_in) + z_in, -128, 127).astype(np.int8)
    Y = np.empty_like(X)
    for i in range(len(Q)):
        interp.set_tensor(inp["index"], Q[i:i + 1])
        interp.invoke()
        Y[i] = (interp.get_tensor(out["index"])[0].astype(np.float32) - z_out) * s_out
    return Y


def mse(X, Y):
    return np.mean((X - Y) ** 2, axis=1)


def write_model_header(path, data):
    with open(path, "w") as f:
        f.write("// Auto-generated by ml/convert_tflite.py. Do not edit.\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write("alignas(16) const unsigned char g_model[] = {\n")
        for i in range(0, len(data), 12):
            f.write("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 12]) + ",\n")
        f.write("};\n")
        f.write(f"const unsigned int g_model_len = {len(data)};\n")


def write_params_header(path, p):
    fl = lambda v: f"{float(v):.9g}f"
    with open(path, "w") as f:
        f.write("// Auto-generated by ml/convert_tflite.py. Do not edit.\n#pragma once\n\n")
        f.write(f"// Feature order: {', '.join(p['features'])}\n")
        f.write(f"constexpr int kNumFeatures = {len(p['features'])};\n")
        f.write("constexpr float kMean[] = {" + ", ".join(fl(v) for v in p["mean"]) + "};\n")
        f.write("constexpr float kStd[] = {" + ", ".join(fl(v) for v in p["std"]) + "};\n")
        f.write(f"constexpr float kInputScale = {fl(p['input_scale'])};\n")
        f.write(f"constexpr int kInputZeroPoint = {int(p['input_zero_point'])};\n")
        f.write(f"constexpr float kOutputScale = {fl(p['output_scale'])};\n")
        f.write(f"constexpr int kOutputZeroPoint = {int(p['output_zero_point'])};\n")
        f.write(f"constexpr float kTau = {fl(p['tau_int8'])};  // anomaly if MSE > kTau\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--train", nargs="+", required=True, help="same CSVs used for training")
    ap.add_argument("--model-dir", default="models/real")
    ap.add_argument("--eval", default=None, help="CSV with a 0/1 'label' column")
    ap.add_argument("--block", type=int, default=180, help="same value as in training")
    ap.add_argument("--reps", type=int, default=500, help="representative samples for calibration")
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()
    d = args.model_dir
    rng = np.random.default_rng(args.seed)

    with open(os.path.join(d, "scaler.json")) as f:
        scaler = json.load(f)
    with open(os.path.join(d, "threshold_float.json")) as f:
        thr = json.load(f)
    features = scaler["features"]
    mu = np.array(scaler["mean"], dtype="float32")
    sd = np.array(scaler["std"], dtype="float32")
    percentile = thr["percentile"]
    norm = lambda a: ((a - mu) / sd).astype("float32")   # saved scaler, never refitted

    print("sessions:")
    df = load(args.train, features)
    X = norm(df[features].to_numpy("float32"))
    tr, va, te = block_split(len(X), args.block)
    Xtr, Xva, Xte = X[tr], X[va], X[te]
    print(f"rows: train={len(Xtr)} val={len(Xva)} test={len(Xte)}  (must match the training log)")

    model = keras.models.load_model(os.path.join(d, "ae_float.keras"))
    saved = os.path.join(d, "saved_model")
    model.export(saved)

    # Representative dataset: real normalized TRAIN samples. The converter uses them to
    # measure each tensor's value range and choose the INT8 scale / zero point.
    reps = Xtr[rng.choice(len(Xtr), size=min(args.reps, len(Xtr)), replace=False)]

    def rep_gen():
        for x in reps:
            yield [x[None, :].astype("float32")]

    conv = tf.lite.TFLiteConverter.from_saved_model(saved)
    conv.optimizations = [tf.lite.Optimize.DEFAULT]
    conv.representative_dataset = rep_gen
    conv.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    conv.inference_input_type = tf.int8
    conv.inference_output_type = tf.int8
    tflite_model = conv.convert()
    with open(os.path.join(d, "model_int8.tflite"), "wb") as f:
        f.write(tflite_model)
    print(f"\nmodel_int8.tflite: {len(tflite_model)} bytes")

    interp = get_interpreter_class()(model_content=tflite_model)
    interp.allocate_tensors()
    inp = interp.get_input_details()[0]
    out = interp.get_output_details()[0]
    s_in, z_in = inp["quantization"]
    s_out, z_out = out["quantization"]
    print(f"input  int8: scale={s_in:.6g} zero_point={z_in}")
    print(f"output int8: scale={s_out:.6g} zero_point={z_out}")

    def errors(Xs):
        return mse(Xs, model.predict(Xs, verbose=0, batch_size=1024)), mse(Xs, run_int8(interp, Xs))

    ef_va, eq_va = errors(Xva)
    ef_te, eq_te = errors(Xte)
    tau_f = float(np.percentile(ef_va, percentile))
    tau_q = float(np.percentile(eq_va, percentile))
    floor = (s_out ** 2) / 12.0   # rounding noise of the output layer alone (a lower bound)

    print(f"\ntau_float: {tau_f:.3e} (training log said {thr['tau']:.3e}; should match)")
    if abs(tau_f - thr["tau"]) > 1e-3 * max(thr["tau"], 1e-12):
        print("  WARNING: mismatch -> --train files or --block differ from training")
    print("Float vs INT8 reconstruction error on validation data")
    print(f"  median: float {np.median(ef_va):.2e}  int8 {np.median(eq_va):.2e}")
    print(f"  p{percentile:g}:   float {tau_f:.2e}  int8 {tau_q:.2e}  ratio {tau_q / tau_f:.2f}")
    print(f"  correlation of per-sample errors: {np.corrcoef(ef_va, eq_va)[0, 1]:.4f}")
    print(f"  output rounding floor (s_out^2/12): {floor:.2e}")
    if tau_q < 10 * floor:
        print("  WARNING: tau is within 10x of the quantization floor; alarms will be unstable")
    print(f"\nnormal test FPR: float {(ef_te > tau_f).mean():.3f}   "
          f"int8 with tau_int8 {(eq_te > tau_q).mean():.3f}   "
          f"int8 with the float tau {(eq_te > tau_f).mean():.3f}")

    if args.eval:
        print("\neval file:")
        de = load(args.eval, features)
        Xe = norm(de[features].to_numpy("float32"))
        y = de["label"].to_numpy().astype(int)
        ef, eq = errors(Xe)
        for name, e, t in (("float", ef, tau_f), ("int8 ", eq, tau_q)):
            pred = (e > t).astype(int)
            p, r, f1, _ = precision_recall_fscore_support(y, pred, average="binary",
                                                          zero_division=0)
            print(f"  {name}: AUC={roc_auc_score(y, e):.3f} precision={p:.3f} "
                  f"recall={r:.3f} F1={f1:.3f} FPR={pred[y == 0].mean():.3f}")

    params = {"features": features, "mean": mu.tolist(), "std": sd.tolist(),
              "percentile": percentile, "tau_float": tau_f, "tau_int8": tau_q,
              "input_scale": float(s_in), "input_zero_point": int(z_in),
              "output_scale": float(s_out), "output_zero_point": int(z_out),
              "model_bytes": len(tflite_model), "n_val": int(len(Xva)), "reps": int(len(reps))}
    with open(os.path.join(d, "thresholds_int8.json"), "w") as f:
        json.dump(params, f, indent=2)
    write_model_header(os.path.join(d, "model_data.h"), tflite_model)
    write_params_header(os.path.join(d, "model_params.h"), params)
    print(f"\nwrote model_int8.tflite, thresholds_int8.json, model_data.h, model_params.h in {d}")


if __name__ == "__main__":
    main()